// Bundle the CLI into a single dependency-free file used by the GitHub Action.
import { build } from "esbuild";
import { chmod } from "node:fs/promises";

await build({
  entryPoints: ["src/bin.ts"],
  outfile: "dist/cli.js",
  bundle: true,
  platform: "node",
  target: "node18",
  format: "esm",
  minify: false,
  legalComments: "none",
  banner: { js: "// Generated by `npm run build` from src/ — do not edit.\n" },
});
await chmod("dist/cli.js", 0o755);
console.log("built dist/cli.js");
